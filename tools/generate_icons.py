#!/usr/bin/env python3
"""Convert the pinned Lucide subset with development-only FontTools 4.55.3."""
from pathlib import Path
import xml.etree.ElementTree as ET
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen

root = Path(__file__).resolve().parents[1]
names = {'Clear': 'trash-2', 'Marker': 'map-pin', 'Area': 'pentagon', 'Map': 'globe', 'Edit': 'pencil', 'Move': 'move'}
lines = ['// Generated by tools/generate_icons.py. See third_party/lucide/LICENSE.', 'QPainterPath iconPath(UiIcon icon)', '{', '    QPainterPath path;', '    switch (icon) {']
def number(value):
    return format(value, '.10g')
for name, file in names.items():
    lines.append('    case UiIcon::' + name + ':')
    for node in ET.parse(root / 'third_party/lucide' / (file + '.svg')).getroot():
        tag = node.tag.rsplit('}', 1)[-1]
        if tag == 'circle':
            x, y, r = (float(node.attrib[key]) for key in ('cx', 'cy', 'r'))
            lines.append(f'        path.addEllipse(QPointF({number(x)}, {number(y)}), {number(r)}, {number(r)});')
            continue
        if tag == 'line':
            path = f"M{node.attrib['x1']} {node.attrib['y1']}L{node.attrib['x2']} {node.attrib['y2']}"
        else:
            assert tag == 'path'
            path = node.attrib['d']
        pen = RecordingPen()
        parse_path(path, pen)
        for operation, points in pen.value:
            if operation == 'endPath':
                continue
            method = {'moveTo': 'moveTo', 'lineTo': 'lineTo', 'curveTo': 'cubicTo', 'closePath': 'closeSubpath'}[operation]
            args = ', '.join(number(v) for point in points for v in point)
            lines.append(f'        path.{method}({args});')
    lines.append('        break;')
lines.extend(['    case UiIcon::Circle:', '        path.addEllipse(QPointF(12, 12), 9, 9);', '        break;', '    case UiIcon::Line:', '        path.moveTo(4, 20); path.lineTo(20, 4);', '        path.addEllipse(QPointF(4, 20), 1.5, 1.5); path.addEllipse(QPointF(20, 4), 1.5, 1.5);', '        break;', '    case UiIcon::Distance:', '        path.moveTo(3, 17); path.lineTo(17, 3); path.lineTo(21, 7); path.lineTo(7, 21); path.closeSubpath();', '        path.moveTo(7, 13); path.lineTo(9, 15); path.moveTo(11, 9); path.lineTo(13, 11); path.moveTo(15, 5); path.lineTo(17, 7);', '        break;'])
lines.extend(['    case UiIcon::Lock:', '    case UiIcon::Unlock:', '        path.addRoundedRect(QRectF(5, 10, 14, 11), 2, 2);', '        path.moveTo(8, 10); path.lineTo(8, 7); path.cubicTo(8, 1, 16, 1, 16, 7);', '        if (icon == UiIcon::Lock) path.lineTo(16, 10);', '        path.moveTo(12, 14); path.lineTo(12, 17);', '        break;'])
lines.extend(['    case UiIcon::Server:', '        path.addRoundedRect(QRectF(3, 3, 18, 7), 2, 2); path.addRoundedRect(QRectF(3, 14, 18, 7), 2, 2);', '        path.moveTo(7, 6); path.lineTo(7, 7); path.moveTo(7, 17); path.lineTo(7, 18);', '        break;', '    case UiIcon::Data:', '        path.moveTo(3, 7); path.lineTo(12, 2); path.lineTo(21, 7); path.lineTo(12, 12); path.closeSubpath();', '        path.moveTo(3, 12); path.lineTo(12, 17); path.lineTo(21, 12);', '        path.moveTo(3, 17); path.lineTo(12, 22); path.lineTo(21, 17);', '        break;'])
lines.extend(['    case UiIcon::Confirm:', '        path.moveTo(4, 12); path.lineTo(9, 17); path.lineTo(20, 6);', '        break;', '    case UiIcon::Apply:', '        path.moveTo(4, 3); path.lineTo(17, 3); path.lineTo(21, 7); path.lineTo(21, 21); path.lineTo(3, 21); path.lineTo(3, 3); path.closeSubpath();', '        path.addRect(QRectF(7, 3, 9, 6)); path.addRect(QRectF(7, 14, 10, 7));', '        break;'])
lines.extend(['    }', '    return path;', '}'])
(root / 'src/core/ui_icon_paths.inc').write_text('\n'.join(lines) + '\n')
